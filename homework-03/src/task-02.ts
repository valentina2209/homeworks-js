/**
 * З клавіатури вводиться ціна товару і кількість грошей. 
 * Якщо грошей не вистачає то відмовляємо у покупці, 
 * інакше, якщо ще залишаються гроші, 
 * то пропонуємо купити лотерею за 4 грн.
 */

const priceProduct = parseInt(prompt("Введіть ціну за товар, грн")!)
const amountMoney = parseInt(prompt("Введіть кількість грошей, грн")!)


if (priceProduct > amountMoney || amountMoney === 0) {
    alert("Вибачте, на вашому рахунку не достатньо грошей")
} else {
    alert("Вітаємо з вдалою покупкою")

    if (amountMoney - priceProduct >= 4) {
        alert( "Бажаєте придбати лотерею за 4 грн?" )
    }
}
    

